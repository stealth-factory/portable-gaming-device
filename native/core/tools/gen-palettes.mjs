// Writes native/core/include/pgd/palettes.hpp from the web console's phosphor modes
// (src/kit/platform/palettes.ts), so the native core and the web cannot drift apart.
// Run: node native/core/tools/gen-palettes.mjs   (tests/unit/native-palettes.test.ts checks it is current)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MODES, MODE_ORDER } from '../../../src/kit/platform/palettes.ts';

export const OUT = fileURLToPath(new URL('../include/pgd/palettes.hpp', import.meta.url));

const rgb = hex => `{ ${[1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)).join(', ')} }`;
const num = v => (Number.isInteger(v) ? v.toFixed(1) : String(v));

export function palettesHeader() {
  // modes share role maps (monochrome and CGA); emit each distinct map once
  const maps = [];
  const mapOf = roles => {
    const key = JSON.stringify(roles);
    let i = maps.findIndex(m => m.key === key);
    if (i < 0) { i = maps.length; maps.push({ key, roles }); }
    return i;
  };
  const modes = MODE_ORDER.map(k => ({ k, m: MODES[k], map: mapOf(MODES[k].roles) }));
  const lines = [
    '// Generated by native/core/tools/gen-palettes.mjs from src/kit/platform/palettes.ts. Do not edit.',
    '#pragma once',
    '#include <cstdint>',
    '',
    'namespace pgd {',
    '',
    'struct RoleIndex { const char* role; std::uint8_t index; };',
    'struct RoleMap { const RoleIndex* entries; int count; };',
    '',
    '/** A phosphor mode: four colours, role map, the palette indices that tint the set\'s lights (phos, phos2), glow half-life (s),',
    '    bloom, stripe mask, radar sweep period (s, 0 for none) and the bezel (highlight, body, shadow, plate ink, unlit glass). */',
    'struct PhosphorMode {',
    '  const char* key;',
    '  const char* name;',
    '  std::uint8_t pal[4][3];',
    '  const RoleMap* roles;',
    '  std::uint8_t phos, phos2;',
    '  double half, bloom;',
    '  bool mask;',
    '  double sweep;',
    '  std::uint8_t bezel[5][3];',
    '};',
    '',
  ];
  maps.forEach((m, i) => {
    const entries = Object.entries(m.roles).map(([r, v]) => `{ "${r}", ${v} }`);
    lines.push(`inline constexpr RoleIndex kRoles${i}[] = {`);
    for (let j = 0; j < entries.length; j += 6) lines.push('  ' + entries.slice(j, j + 6).join(', ') + ',');
    lines.push('};');
    lines.push(`inline constexpr RoleMap kRoleMap${i} = { kRoles${i}, ${Object.keys(m.roles).length} };`);
    lines.push('');
  });
  lines.push(`inline constexpr int kModeCount = ${modes.length};`);
  lines.push('/** In the phosphor dial\'s order. */');
  lines.push('inline constexpr PhosphorMode kModes[kModeCount] = {');
  for (const { k, m, map } of modes) {
    lines.push(`  { "${k}", "${m.name}", { ${m.pal.map(rgb).join(', ')} }, &kRoleMap${map}, ${m.phos}, ${m.phos2}, ${num(m.half)}, ${num(m.bloom)}, ${m.mask}, ${num(m.sweep ?? 0)},`);
    lines.push(`    { ${m.bezel.map(rgb).join(', ')} } },`);
  }
  lines.push('};', '', '}  // namespace pgd', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, palettesHeader());
  console.log('wrote', OUT);
}
