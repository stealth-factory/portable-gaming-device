// Bake the pinned Silkscreen font into the native core's bitmap atlas (GAM-35):
//   node tools/fonts/atlas.cjs
// It draws every glyph in the font's character map at the console's two sizes, 8 and 16 px, in
// Chromium (the same text drawing the web console uses, `textBaseline = 'top'`), and writes
// native/core/include/pgd/font_atlas.hpp. Silkscreen sits on a 125-unit grid, so at these sizes glyphs
// land on whole pixels. A few curves and accents leave faint grey edges; a pixel counts as lit at half
// coverage or more, which is where the web console's four-colour quantiser puts them against the
// background. The script lists any grey pixels it saw so a font change that blurs more shows up.
// Needs Playwright with Chromium. Re-run it only when the font changes; a unit test checks the atlas
// still matches the font's hash and advances in src/kit/platform/font-metrics.json.
const { chromium } = require('playwright');
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');

const ROOT = join(__dirname, '../..');
const FONT = join(__dirname, 'Silkscreen-Regular.ttf');
const METRICS = JSON.parse(readFileSync(join(ROOT, 'src/kit/platform/font-metrics.json'), 'utf8'));
const OUT = join(ROOT, 'native/core/include/pgd/font_atlas.hpp');
const SIZES = [8, 16];

(async () => {
  const codes = Object.keys(METRICS.advances).map(Number).filter(c => c >= 32).sort((a, b) => a - b);
  const b = await chromium.launch();
  const p = await b.newPage();
  await p.setContent('<canvas id="c" width="64" height="64"></canvas>');
  const font = readFileSync(FONT).toString('base64');
  const baked = await p.evaluate(async ({ font, codes, sizes }) => {
    const face = new FontFace('Silkscreen', Uint8Array.from(atob(font), c => c.charCodeAt(0)));
    document.fonts.add(await face.load());
    const cv = document.getElementById('c'), g = cv.getContext('2d', { willReadFrequently: true });
    const PAD = 16, out = {};
    for (const size of sizes) {
      out[size] = [];
      for (const code of codes) {
        g.clearRect(0, 0, 64, 64);
        g.font = `${size}px Silkscreen`; g.textBaseline = 'top'; g.textAlign = 'left'; g.fillStyle = '#fff';
        g.fillText(String.fromCodePoint(code), PAD, PAD);
        const d = g.getImageData(0, 0, 64, 64).data;
        const grey = []; let x0 = 64, y0 = 64, x1 = -1, y1 = -1;
        const on = [];
        for (let y = 0; y < 64; y++) for (let x = 0; x < 64; x++) {
          const a = d[(y * 64 + x) * 4 + 3];
          if (a > 0 && a < 255) grey.push(a);
          if (a >= 128) { on.push([x, y]); x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); }
        }
        const glyph = { code, advance: g.measureText(String.fromCodePoint(code)).width, grey, x: 0, y: 0, w: 0, h: 0, rows: [] };
        if (on.length) {
          glyph.x = x0 - PAD; glyph.y = y0 - PAD; glyph.w = x1 - x0 + 1; glyph.h = y1 - y0 + 1;
          glyph.rows = Array.from({ length: glyph.h }, () => 0);
          for (const [x, y] of on) glyph.rows[y - y0] |= 1 << (x - x0);
        }
        out[size].push(glyph);
      }
    }
    return out;
  }, { font, codes, sizes: SIZES });
  await b.close();

  const lines = [], greys = [];
  for (const size of SIZES) {
    const bits = [], glyphs = [];
    for (const gl of baked[size]) {
      if (gl.grey.length) greys.push(`U+${gl.code.toString(16)}@${size}: ${gl.grey.join(' ')}`);
      const want = (METRICS.advances[gl.code] * size) / METRICS.unitsPerEm;
      if (Math.abs(gl.advance - want) > 0.01 || want !== Math.round(want)) throw new Error(`U+${gl.code.toString(16)} at ${size} px advances ${gl.advance}, the metrics say ${want}`);
      gl.advance = want;   // the browser's measure carries float noise; the metrics are exact
      if (gl.w > 32) throw new Error(`U+${gl.code.toString(16)} at ${size} px is wider than 32`);
      glyphs.push(`  {${gl.code}, ${gl.advance}, ${gl.x}, ${gl.y}, ${gl.w}, ${gl.h}, ${bits.length}},`);
      bits.push(...gl.rows);
    }
    lines.push(
      `inline constexpr std::uint32_t kRows${size}[] = {`,
      ...chunk(bits.map(v => `0x${v.toString(16)}`), 12).map(r => '  ' + r.join(', ') + ','),
      '};',
      `inline constexpr Glyph kGlyphs${size}[] = {`,
      ...glyphs,
      '};',
      '',
    );
  }
  if (greys.length) console.log("grey pixels:\n" + greys.join("\n"));
  const count = baked[SIZES[0]].length;
  writeFileSync(OUT, `// Generated by tools/fonts/atlas.cjs from tools/fonts/Silkscreen-Regular.ttf. Do not edit.
// Silkscreen: Copyright 2001 The Silkscreen Project Authors, SIL Open Font License 1.1 (tools/fonts/OFL.txt).
#pragma once
#include <cstdint>

namespace pgd::font {

/** The font file these bitmaps were baked from (its SHA-256, as in src/kit/platform/font-metrics.json). */
inline constexpr const char* kSourceSha256 = "${METRICS.sha256}";
/** Pen advance, in whole pixels at 8 px, for a character the font does not have. */
inline constexpr int kMissingAdvance8 = ${(METRICS.missingAdvance * 8) / METRICS.unitsPerEm};

/** One glyph: its code point, advance, and the box of lit pixels relative to the pen's top-left
    (\`textBaseline = 'top'\`). Row r of the box is rows[first + r]; bit c is column c. */
struct Glyph { std::uint32_t code; std::int8_t advance, x, y; std::uint8_t w, h; std::uint16_t first; };

inline constexpr int kGlyphCount = ${count};

${lines.join('\n')}} // namespace pgd::font
`);
  console.log(`wrote ${OUT}: ${count} glyphs at ${SIZES.join(' and ')} px`);
})().catch(e => { console.error(e); process.exit(1); });

function chunk(a, n){ const out = []; for (let i = 0; i < a.length; i += n) out.push(a.slice(i, i + n)); return out; }
